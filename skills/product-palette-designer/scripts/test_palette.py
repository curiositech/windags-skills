def valid_spec():
    themes = {}
    for theme, background, foreground in (("light", "oklch(1 0 0)", "oklch(0 0 0)"),
                                           ("dark", "oklch(0 0 0)", "oklch(1 0 0)")):
        tokens = {token: background for token in palette.REQUIRED}
        tokens.update({"foreground": foreground, "link": foreground,
                       "focus": foreground, "ring": foreground, "sidebar-ring": foreground})
        for surface in palette.SURFACES:
            tokens[surface] = background
            tokens[surface + "-foreground"] = foreground
        tokens["primary"] = foreground
        tokens["primary-foreground"] = background
        tokens["primary-hover"] = foreground
        tokens["primary-active"] = foreground
        tokens["sidebar"] = background
        themes[theme] = tokens
    return {"name": "Fixture", "families": {"neutral": {"h": 0, "c": 0, "uses": ["UI surfaces"]},
             "red": {"h": 25, "c": .25, "uses": ["Warning"]}}, "themes": themes,
            "pairs": [{"theme": theme, "fg": "foreground", "bg": "background", "min": 4.5, "purpose": "Body text"}
                      for theme in ("light", "dark")], "coverage": {"maxGap": 75}}


class ColorMathTests(unittest.TestCase):
    def test_black_white_is_21_to_1(self):
        self.assertEqual(palette.contrast_ratio((0, 0, 0), (1, 1, 1)), 21)
        self.assertEqual(palette.contrast_ratio((1, 1, 1), (0, 0, 0)), 21)
        self.assertEqual(palette.contrast_ratio((.4, .4, .4), (.4, .4, .4)), 1)

    def test_ottosson_primary_srgb_fixtures(self):
        # Independent published 2021 matrix outputs, not generated by this code:
        # https://bottosson.github.io/posts/oklab/ . Values rounded to 7 decimals.
        fixtures = [((1, 0, 0), (.6279554, .2248631, .1258463)),
                    ((0, 1, 0), (.8664396, -.2338876, .1794985)),
                    ((0, 0, 1), (.4520137, -.0324570, -.3115281))]
        for rgb, lab in fixtures:
            with self.subTest(rgb=rgb):
                for actual, expected in zip(palette.srgb_to_oklab(*rgb), lab):
                    self.assertAlmostEqual(actual, expected, places=6)
                converted = tuple(palette.linear_to_srgb(x) for x in palette.oklab_to_linear_rgb(*lab))
                for actual, expected in zip(converted, rgb):
                    self.assertAlmostEqual(actual, expected, delta=3e-6)

    def test_transfer_threshold_and_round_trip(self):
        self.assertEqual(palette.srgb_to_linear(.04045), .04045 / 12.92)
        for value in (-.4, 0, .02, .04045, .5, 1):
            self.assertAlmostEqual(palette.linear_to_srgb(palette.srgb_to_linear(value)), value, delta=3e-8)

    def test_gamut_reduction_preserves_lightness_hue_without_excursions(self):
        for hue in range(0, 360, 17):
            for lightness in (0, .01, .2, .5, .8, .99, 1):
                with self.subTest(hue=hue, lightness=lightness):
                    lch, rgb, mapped = palette.gamut_map(lightness, .8, hue)
                    self.assertTrue(mapped)
                    self.assertEqual(lch[0], lightness)
                    self.assertEqual(lch[2], hue)
                    self.assertLess(lch[1], .8)
                    self.assertTrue(all(0 <= value <= 1 for value in rgb))
                    self.assertTrue(palette.in_gamut(palette.oklch_to_srgb(*lch)))

    def test_large_finite_chroma_cannot_overflow_mapper(self):
        lch, rgb, mapped = palette.gamut_map(.5, 1e300, 47)
        self.assertTrue(mapped)
        self.assertTrue(all(0 <= value <= 1 for value in rgb))
        self.assertLess(lch[1], 1)

    def test_hue_wrap_and_achromatic_color(self):
        self.assertEqual(palette.gamut_map(.5, .1, -30)[0], palette.gamut_map(.5, .1, 330)[0])
        self.assertEqual(palette.gamut_map(.5, .1, 690)[0], palette.gamut_map(.5, .1, 330)[0])
        a = palette.color_record(.5, 0, 30)
        b = palette.color_record(.5, 0, 200)
        self.assertEqual(a["srgb"], b["srgb"])
        self.assertAlmostEqual(a["srgb"]["rgb"][0], a["srgb"]["rgb"][1], places=7)


class AuditTests(unittest.TestCase):
    def setUp(self):
        self.spec = valid_spec()

    def test_complete_spec_and_full_ramps(self):
        report = palette.audit(self.spec)
        self.assertEqual(report["errors"], [])
        self.assertEqual(set(report["themes"]["light"]), set(palette.REQUIRED))
        self.assertEqual(list(report["ramps"]["red"]), [str(step) for step in palette.STEPS])
        for step, lightness in zip(palette.STEPS, palette.LIGHTNESS):
            self.assertEqual(report["ramps"]["red"][str(step)]["oklch"][0], lightness)
        self.assertTrue(all(row["pass"] for row in report["contrast"]))

    def test_literal_out_of_gamut_is_reported_not_silently_clipped(self):
        self.spec["themes"]["light"]["chart-1"] = "oklch(.7 .8 20)"
        report = palette.audit(self.spec)
        color = report["themes"]["light"]["chart-1"]
        self.assertTrue(color["mapped"])
        self.assertEqual(color["requestedOklch"], [.7, .8, 20])
        self.assertIn("themes.light.chart-1", report["mapping"]["mappedColors"])
        self.assertIn("not the CSS", report["mapping"]["policy"])

    def test_alias_chain_is_resolved(self):
        self.spec["themes"]["light"]["ink"] = "neutral.950"
        self.spec["themes"]["light"]["ink-alias"] = "$ink"
        self.spec["themes"]["light"]["foreground"] = "$ink-alias"
        self.spec["themes"]["dark"]["ink"] = "$foreground"
        self.spec["themes"]["dark"]["ink-alias"] = "$ink"
        report = palette.audit(self.spec)
        self.assertEqual(report["errors"], [])
        self.assertEqual(report["themes"]["light"]["foreground"], report["ramps"]["neutral"]["950"])

    def test_optional_semantic_tokens_must_exist_in_both_themes(self):
        self.spec["themes"]["light"]["custom-role"] = "$foreground"
        self.assertTrue(any("semantic token sets must match" in x for x in palette.audit(self.spec)["errors"]))
        self.spec["themes"]["dark"]["custom-role"] = "$foreground"
        self.assertEqual(palette.audit(self.spec)["errors"], [])

    def test_alias_unknown_and_cycle(self):
        for definitions, error in (({"foreground": "$missing"}, "unknown alias target"),
                                   ({"foreground": "$link", "link": "$foreground"}, "alias cycle")):
            with self.subTest(definitions=definitions):
                self.spec = valid_spec()
                self.spec["themes"]["light"].update(definitions)
                self.assertTrue(any(error in message for message in palette.audit(self.spec)["errors"]))

    def test_missing_tokens_and_explicit_dark_rejected(self):
        del self.spec["themes"]["dark"]
        del self.spec["themes"]["light"]["selection-foreground"]
        errors = palette.audit(self.spec)["errors"]
        self.assertTrue(any("exactly light and dark" in x for x in errors))
        self.assertTrue(any("missing tokens: selection-foreground" in x for x in errors))

    def test_bool_null_nan_inf_and_negative_family_inputs_rejected(self):
        for key, invalid in (("h", True), ("h", None), ("h", float("nan")),
                             ("h", float("inf")), ("c", -.1), ("c", "0.2")):
            with self.subTest(key=key, invalid=invalid):
                spec = valid_spec()
                spec["families"]["red"][key] = invalid
                self.assertTrue(any("finite numeric" in x for x in palette.audit(spec)["errors"]))

    def test_bad_literals_and_family_steps_rejected(self):
        for expression in ("#ffffff", "oklch(50% .1 20)", "oklch(.5 .1 20 / .5)",
                           "oklch(2 .1 20)", "oklch(.5 -.1 20)", "oklch(.5 .1 1e999)",
                           "red.75", "red.500; color:red", "url(example.com)", None, True):
            with self.subTest(expression=expression):
                spec = valid_spec()
                spec["themes"]["light"]["chart-1"] = expression
                self.assertTrue(palette.audit(spec)["errors"])

    def test_invalid_pair_shape_threshold_and_both_themes(self):
        for pairs in ([], [{"theme": "light"}],
                      [{"theme": "light", "fg": "foreground", "bg": "background", "min": True, "purpose": "text"}],
                      [{"theme": "light", "fg": "foreground", "bg": "background", "min": 3, "purpose": "text"}],
                      [{"theme": "light", "fg": "absent", "bg": "background", "min": 4.5, "purpose": "text"}],
                      [valid_spec()["pairs"][0]]):
            with self.subTest(pairs=pairs):
                spec = valid_spec()
                spec["pairs"] = pairs
                self.assertTrue(palette.audit(spec)["errors"])

    def test_required_pairs_cannot_be_omitted_by_author(self):
        self.spec["themes"]["light"]["warning"] = "oklch(1 0 0)"
        self.spec["themes"]["light"]["warning-foreground"] = "oklch(.9 0 0)"
        self.assertTrue(any("warning-foreground/warning contrast" in x for x in palette.audit(self.spec)["errors"]))

    def test_unrounded_4_point_499_is_a_failure(self):
        # A neutral OKLab L has linear RGB = L^3. Against black, target ratio
        # 4.499 gives Y = 4.499*.05-.05; the displayed 2-decimal ratio is 4.50.
        target = 4.499
        l = (target * .05 - .05) ** (1 / 3)
        self.spec["themes"]["dark"]["foreground"] = f"oklch({l:.17g} 0 0)"
        report = palette.audit(self.spec)
        row = next(row for row in report["contrast"] if row["theme"] == "dark" and row["fg"] == "foreground")
        self.assertAlmostEqual(row["ratio"], target, places=10)
        self.assertEqual(format(row["ratio"], ".2f"), "4.50")
        self.assertFalse(row["pass"])
        self.assertTrue(report["errors"])

    def test_hue_coverage_excludes_neutrals_and_wraps(self):
        self.spec["families"] = {"a": {"h": -10, "c": .1, "uses": ["a"]},
                                 "b": {"h": 10, "c": .1, "uses": ["b"]},
                                 "neutral": {"h": 180, "c": .019, "uses": ["UI"]}}
        report = palette.audit(self.spec)
        self.assertEqual(report["coverage"]["chromaticHues"], [10, 350])
        self.assertEqual(report["coverage"]["cyclicGaps"], [340, 20])
        self.assertEqual(report["coverage"]["maxGap"], 340)
        self.assertTrue(any("coverage is descriptive" in x for x in report["warnings"]))

    def test_css_namespace_collision_rejected(self):
        self.spec["themes"]["light"]["red-500"] = "$foreground"
        self.assertTrue(any("collides" in x for x in palette.audit(self.spec)["errors"]))


class ExportTests(unittest.TestCase):
    def test_tailwind4_namespaces_and_no_undefined_variables(self):
        report = palette.audit(valid_spec())
        css = palette.render_css(report)
        self.assertIn('@import "tailwindcss";', css)
        self.assertIn("@theme inline", css)
        self.assertIn("@custom-variant dark", css)
        self.assertIn("--color-red-950:", css)
        for token in palette.REQUIRED:
            self.assertIn("--color-" + token + ": var(--" + token + ");", css)
        declarations = set(re.findall(r"(--[a-z0-9-]+)\s*:", css))
        references = set(re.findall(r"var\((--[a-z0-9-]+)\)", css))
        self.assertLessEqual(references, declarations)

    def test_preview_escapes_authored_text_and_uses_real_tokens(self):
        spec = valid_spec()
        spec["name"] = '</title><script>alert("oops")</script>'
        spec["families"]["red"]["uses"] = ["<img src=x onerror=alert(1)>"]
        preview = palette.render_preview(palette.audit(spec), spec)
        self.assertNotIn('<script>', preview)
        self.assertNotIn('<img src=x', preview)
        self.assertIn("&lt;script&gt;", preview)
        self.assertIn("&lt;img", preview)
        self.assertIn("background:var(--primary)", preview)
        self.assertIn("background:var(--chart-", preview)
        self.assertIn('class="hue-wheel"', preview)
        self.assertIn('role="img"', preview)
        self.assertIn('class="brand-art"', preview)
        self.assertIn('var(--color-red-500)', preview)
        self.assertIn('aria-pressed="true"', preview)
        self.assertIn(' disabled', preview)
        self.assertIn('Canonical OKLCH coordinates', preview)
        self.assertIn('title="oklch(', preview)
        self.assertNotIn('src="http', preview)
        self.assertNotIn('@import', preview)

    def test_favicon_uses_resolved_foreground_for_pale_primary(self):
        spec = valid_spec()
        for token in ("primary", "primary-hover", "primary-active"):
            spec["themes"]["light"][token] = "oklch(1 0 0)"
        spec["themes"]["light"]["primary-foreground"] = "oklch(0 0 0)"
        report = palette.audit(spec)
        self.assertEqual(report["errors"], [])
        preview = palette.render_preview(report, spec)
        icon = unquote(re.search(r'href="data:image/svg\+xml,([^"]+)"', preview).group(1))
        self.assertIn('fill="#ffffff"', icon)
        self.assertIn('<path d="m16 6 10 10-10 10L6 16Z" fill="#000000"', icon)

    def test_cli_check_no_writes_and_failed_export_creates_nothing(self):
        # Explicit cwd keeps all test scratch inside the calling worktree, never /tmp.
        with tempfile.TemporaryDirectory(prefix="palette-test-", dir=Path.cwd()) as scratch:
            folder = Path(scratch)
            source = folder / "spec.json"
            source.write_text(json.dumps(valid_spec()))
            before = set(folder.iterdir())
            with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(palette.main([str(source), "--check"]), 0)
            self.assertEqual(set(folder.iterdir()), before)
            invalid = valid_spec()
            del invalid["themes"]["dark"]["foreground"]
            source.write_text(json.dumps(invalid))
            with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(palette.main([str(source), "--out", str(folder / "invalid")]), 1)
            self.assertFalse((folder / "invalid").exists())

    def test_cli_exports_three_consistent_artifacts(self):
        with tempfile.TemporaryDirectory(prefix="palette-test-", dir=Path.cwd()) as scratch:
            folder = Path(scratch)
            source = folder / "spec.json"
            source.write_text(json.dumps(valid_spec()))
            with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(palette.main([str(source), "--out", str(folder / "out")]), 0)
            self.assertEqual({x.name for x in (folder / "out").iterdir()}, {"palette.json", "tokens.css", "preview.html"})
            data = json.loads((folder / "out" / "palette.json").read_text())
            self.assertEqual(data["errors"], [])
            token = data["themes"]["light"]["primary"]["css"]
            self.assertIn("--primary: " + token, (folder / "out" / "tokens.css").read_text())
            self.assertIn("--primary: " + token, (folder / "out" / "preview.html").read_text())

    def test_invalid_json_and_nonfinite_number_exit_cleanly(self):
        with tempfile.TemporaryDirectory(prefix="palette-test-", dir=Path.cwd()) as scratch:
            source = Path(scratch) / "spec.json"
            for invalid in ('{"h": NaN}', '{"h": Infinity}', 'not json'):
                source.write_text(invalid)
                with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                    self.assertEqual(palette.main([str(source), "--check"]), 1)


if __name__ == "__main__":
    unittest.main()
